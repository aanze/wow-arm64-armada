#!/usr/bin/env python3
"""Check that the aarch64 syscall thunks of a built ntdll.dll load the
dispatcher pointer from the fixed address 0x7ffe1000.

Each thunk generated by __ASM_SYSCALL_FUNC (include/wine/asm.h) ends with:

    ldr x16, 1f        90 00 00 58
    ldr x16, [x16]     10 02 40 f9
    blr x16            00 02 3f d6
    ret                c0 03 5f d6
 1: .quad 0x7ffe1000   00 10 fe 7f 00 00 00 00

Usage: check-thunks.py ntdll.dll [...]
Exits non-zero if a file contains no patched thunk.
"""

import sys

PATCHED = bytes.fromhex("90000058 100240f9 00023fd6 c0035fd6 0010fe7f00000000".replace(" ", ""))
TAIL = PATCHED[:16]  # the instructions alone, whatever the literal is

status = 0
for path in sys.argv[1:]:
    with open(path, "rb") as f:
        data = f.read()
    patched = data.count(PATCHED)
    total = data.count(TAIL)
    print(f"{path}: {patched} thunks use 0x7ffe1000 / {total} aarch64 syscall thunks")
    if patched == 0 or patched != total:
        status = 1
sys.exit(status)
